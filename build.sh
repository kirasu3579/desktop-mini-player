#!/usr/bin/env bash
# 无 Gradle 构建脚本：javac 编译 -> 组装 spmod（META-INF/ + classes/ + lib/）
# 结构与官方 WorkshopPluginTask 一致：jar 内容平铺进 classes/，运行期依赖 jar 进 lib/
set -euo pipefail

# javac.exe 是 Windows 原生程序，不认 Git Bash 的 /e/... 路径，所以优先取 pwd -W 的
# E:/... 形式；非 Git Bash 环境（无 -W）退回普通 pwd。
PROJ="$(cd "$(dirname "${BASH_SOURCE[0]}")" && { pwd -W 2>/dev/null || pwd; })"
# 编译期依赖默认放在工程上一级目录，可用环境变量覆盖：
#   JDK_HOME=/path/to/jdk25   SPW_LIBS=/path/to/refs
ROOT="$(dirname "$PROJ")"
JDK="${JDK_HOME:-$ROOT/.tools/unz/jdk25.0.5_0}"
LIBS="${SPW_LIBS:-$ROOT/.refs}"

if [ ! -f "$LIBS/spw-workshop-api.jar" ]; then
  echo "找不到依赖：$LIBS/spw-workshop-api.jar（用 SPW_LIBS 指定依赖目录）" >&2
  exit 1
fi

PLUGIN_ID="com.miniplayer.desktop-mini-player"
# 版本号唯一来源：VERSION.txt。每次改动都要 +1，产物名随之变化，宿主才能识别为新版本。
PLUGIN_VER="$(tr -d '
' < "$PROJ/VERSION.txt")"
if [ -z "$PLUGIN_VER" ]; then
  echo "VERSION.txt 为空，拒绝构建" >&2
  exit 1
fi
PLUGIN_CLASS="com.miniplayer.MiniPlayerPlugin"
OUT_NAME="plugin-${PLUGIN_ID}-${PLUGIN_VER}.spmod"

CP="$LIBS/spw-workshop-api.jar;$LIBS/lib/pf4j-3.12.0.jar;$LIBS/lib/kotlin-stdlib-2.4.20.jar;$LIBS/lib/annotations-13.0.jar"

rm -rf "$PROJ/build/classes" "$PROJ/build/spmod" "$PROJ/build/libs"
STAGE="$PROJ/build/spmod"
mkdir -p "$PROJ/build/classes" "$STAGE/META-INF" "$STAGE/classes/META-INF" "$STAGE/lib" "$PROJ/build/libs"

echo "[1/5] javac"
find "$PROJ/src/main/java" -name "*.java" > "$PROJ/build/sources.txt"
"$JDK/bin/javac.exe" -encoding UTF-8 -proc:none --release 25 \
  -cp "$CP" -d "$PROJ/build/classes" "@$PROJ/build/sources.txt"

echo "[2/5] 类与资源 -> classes/"
cp -r "$PROJ/build/classes/." "$STAGE/classes/"
if [ -d "$PROJ/src/main/resources" ]; then
  cp -r "$PROJ/src/main/resources/." "$STAGE/classes/"
fi

echo "[3/5] PF4J 清单（classes/META-INF/MANIFEST.MF）"
cat > "$STAGE/classes/META-INF/MANIFEST.MF" <<EOF
Manifest-Version: 1.0
Plugin-Class: ${PLUGIN_CLASS}
Plugin-Id: ${PLUGIN_ID}
Plugin-Version: ${PLUGIN_VER}
Plugin-Provider: miniplayer
Plugin-Name: 桌面迷你播放条
Plugin-Description: 桌面悬浮迷你播放条，显示当前曲目与逐字歌词
Plugin-Has-Config: true
Plugin-Open-Source-Url: https://github.com/kirasu3579/desktop-mini-player
Plugin-Permissions: library-read

EOF

# 外层壳清单（与官方打包产物一致，仅版本行）
printf 'Manifest-Version: 1.0\n\n' > "$STAGE/META-INF/MANIFEST.MF"

# extensions.idx 由 resources 带入；若缺失则补写
if [ ! -f "$STAGE/classes/META-INF/extensions.idx" ]; then
  printf '# Generated by PF4J\ncom.miniplayer.MiniPlayerPlaybackExtension\n' \
    > "$STAGE/classes/META-INF/extensions.idx"
fi

echo "[4/5] 运行期依赖 -> lib/"
cp "$LIBS/lib/kotlin-stdlib-2.4.20.jar" "$STAGE/lib/"
cp "$LIBS/lib/annotations-13.0.jar" "$STAGE/lib/"

echo "[5/5] 打包 spmod"
cd "$STAGE"
"$JDK/bin/jar.exe" --create --no-manifest --file "$PROJ/build/libs/$OUT_NAME" .
cd "$PROJ"
echo "OK -> $PROJ/build/libs/$OUT_NAME"
ls -la "$PROJ/build/libs/"
